'use strict';
const {test}=require('node:test');const assert=require('node:assert/strict');
const enabled=!!process.env.FIRESTORE_EMULATOR_HOST;
test('publish → save → request → accept → chat → block → revoke', {skip:!enabled},async()=>{
 const {socialAction,getSharedCard}=require('../index');const {getFirestore}=require('firebase-admin/firestore');const db=getFirestore();
 const call=(uid,action,data={})=>socialAction.run({auth:{uid,token:{email_verified:true}},data:{action,...data}});
 const seed=uid=>({ownerId:uid,label:'Work',identity:{displayName:uid,jobTitle:'Engineer',company:'SECRET COMPANY'},contact:{email:'SECRET EMAIL',phone:'',website:''},theme:{primaryHex:'#C8102E'},visibleFields:['role','company','email'],professional:{},schemaVersion:1});
 await db.doc('users/alice/cards/cardA').set(seed('alice'));await db.doc('users/bob/cards/cardB').set(seed('bob'));
 await assert.rejects(()=>socialAction.run({auth:{uid:'alice',token:{email_verified:false}},data:{action:'publish',cardId:'cardA',fields:[]}}));
 const a=await call('alice','publish',{cardId:'cardA',fields:['role']});const b=await call('bob','publish',{cardId:'cardB',fields:['role']});
 const pub=await getSharedCard.run({data:{publicId:a.id}});assert.equal(pub.email,'');assert.equal(pub.company,'');assert.ok(!JSON.stringify(pub).includes('SECRET'));
 await assert.rejects(()=>call('bob','publish',{cardId:'cardA',fields:[]}));
 await call('bob','save',{publicId:a.id});assert.ok((await db.doc('users/bob/received/'+a.id).get()).exists);
 const request=await call('alice','request',{publicId:b.id,ownPublicId:a.id});
 assert.equal((await call('alice','request',{publicId:b.id,ownPublicId:a.id})).id,request.id);
 await assert.rejects(()=>call('alice','message',{connectionId:request.id,messageId:'first',text:'hello'}));
 await assert.rejects(()=>call('alice','respond',{connectionId:request.id,decision:'accept'}));
 await call('bob','respond',{connectionId:request.id,decision:'accept'});
 await call('alice','message',{connectionId:request.id,messageId:'first',text:'hello'});
 await call('alice','message',{connectionId:request.id,messageId:'first',text:'hello'});
 assert.equal((await db.collection('connections/'+request.id+'/messages').get()).size,1);
 await assert.rejects(()=>call('eve','message',{connectionId:request.id,messageId:'evil',text:'hello'}));
 await call('bob','report',{connectionId:request.id,reason:'Testing moderation'});
 await call('bob','block',{connectionId:request.id});
 await assert.rejects(()=>call('alice','message',{connectionId:request.id,messageId:'second',text:'hello'}));
 await assert.rejects(()=>call('alice','request',{publicId:b.id,ownPublicId:a.id}));
 await call('alice','unpublish',{cardId:'cardA'});
 await assert.rejects(()=>getSharedCard.run({data:{publicId:a.id}}));
});
